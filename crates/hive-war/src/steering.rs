//! Movement steering as weighted actions bridged onto the shared tactics crate.

use bevy::prelude::Vec2;

use swarm_model::SteeringMovementConfig;

/// Inputs for one unit — each vector is already the desired direction for that action (or zero).
#[derive(Clone, Debug)]
pub struct SteeringBlendInput {
    pub flow_dir: Vec2,
    pub separation: Vec2,
    pub chase_dir: Vec2,
    pub retreat_dir: Vec2,
    pub rescue_dir: Vec2,
    pub rescue_strength: f32,
    pub beacon_force: Vec2,
    pub defend_base_dir: Vec2,
    pub defend_base_strength: f32,
    pub should_retreat: bool,
    pub has_chase: bool,
    pub has_beacon: bool,
    pub has_defend_base: bool,
    pub home_rally_dir: Vec2,
    pub home_rally_strength: f32,
    pub has_home_rally: bool,
    pub nearest_enemy_sup: f32,
    pub squad_spread_dir: Vec2,
    pub squad_spread_strength: f32,
    pub squad_follow_dir: Vec2,
    pub squad_follow_strength: f32,
}

pub fn blended_steering_direction(
    cfg: &SteeringMovementConfig,
    input: &SteeringBlendInput,
) -> Vec2 {
    let shared_cfg = swarm_model::SteeringMovementConfig {
        beacon_blend: cfg.beacon_blend,
        beacon_blend_retreat_scale: cfg.beacon_blend_retreat_scale,
        chase_weight_base: cfg.chase_weight_base,
        chase_pursuit_suppression_factor: cfg.chase_pursuit_suppression_factor,
        retreat_blend_weight: cfg.retreat_blend_weight,
        chase_steal_dsq_ratio: cfg.chase_steal_dsq_ratio,
        inertia_blend_per_sec: cfg.inertia_blend_per_sec,
        inertia_zero_decay_per_sec: cfg.inertia_zero_decay_per_sec,
        retreat_power_ratio: cfg.retreat_power_ratio,
        retreat_count_power_ratio: cfg.retreat_count_power_ratio,
        retreat_regroup_mix: cfg.retreat_regroup_mix,
        pursuit_speed_bonus: cfg.pursuit_speed_bonus,
        retreat_speed_bonus: cfg.retreat_speed_bonus,
        goal_arrival_speed_frac: cfg.goal_arrival_speed_frac,
        arrival_rescue_override_min: cfg.arrival_rescue_override_min,
        rescue_ally_suppression_threshold: cfg.rescue_ally_suppression_threshold,
        rescue_urgency_scale: cfg.rescue_urgency_scale,
        rescue_blend_base: cfg.rescue_blend_base,
        flow_w_retreat: cfg.flow_w_retreat,
        flow_w_beacon_chase: cfg.flow_w_beacon_chase,
        flow_w_beacon_no_chase: cfg.flow_w_beacon_no_chase,
        flow_w_chase_no_beacon: cfg.flow_w_chase_no_beacon,
        flow_w_default: cfg.flow_w_default,
        sep_w_retreat: cfg.sep_w_retreat,
        sep_w_beacon_chase: cfg.sep_w_beacon_chase,
        sep_w_beacon_no_chase: cfg.sep_w_beacon_no_chase,
        sep_w_chase_no_beacon: cfg.sep_w_chase_no_beacon,
        sep_w_default: cfg.sep_w_default,
        defend_base_blend: cfg.defend_base_blend,
        defend_base_retreat_suppression: cfg.defend_base_retreat_suppression,
        defend_base_chase_suppression: cfg.defend_base_chase_suppression,
        squad_spread_blend: cfg.squad_spread_blend,
        squad_follow_blend: cfg.squad_follow_blend,
        squad_spread_lateral_scale: cfg.squad_spread_lateral_scale,
        squad_spread_forward_scale: cfg.squad_spread_forward_scale,
        squad_spread_assault_radius: cfg.squad_spread_assault_radius,
        squad_follow_lateral_scale: cfg.squad_follow_lateral_scale,
        squad_follow_depth_scale: cfg.squad_follow_depth_scale,
        squad_follow_catchup_scale: cfg.squad_follow_catchup_scale,
        home_rally_blend: cfg.home_rally_blend,
        home_rally_health_threshold: cfg.home_rally_health_threshold,
        home_rally_chase_suppression: cfg.home_rally_chase_suppression,
    };
    let shared_input = swarm_tactics::SteeringBlendInput {
        flow_dir: input.flow_dir,
        separation: input.separation,
        chase_dir: input.chase_dir,
        retreat_dir: input.retreat_dir,
        rescue_dir: input.rescue_dir,
        rescue_strength: input.rescue_strength,
        beacon_force: input.beacon_force,
        defend_base_dir: input.defend_base_dir,
        defend_base_strength: input.defend_base_strength,
        should_retreat: input.should_retreat,
        has_chase: input.has_chase,
        has_beacon: input.has_beacon,
        has_defend_base: input.has_defend_base,
        home_rally_dir: input.home_rally_dir,
        home_rally_strength: input.home_rally_strength,
        has_home_rally: input.has_home_rally,
        nearest_enemy_sup: input.nearest_enemy_sup,
        squad_spread_dir: input.squad_spread_dir,
        squad_spread_strength: input.squad_spread_strength,
        squad_follow_dir: input.squad_follow_dir,
        squad_follow_strength: input.squad_follow_strength,
    };
    swarm_tactics::blended_steering_direction(&shared_cfg, &shared_input)
}
